/**
 * Emit a static stylesheet containing every built-in theme's CSS variables,
 * scoped by `[data-theme="<name>"]`.
 *
 * Why: `hooks/useTheme.ts` applies a non-default theme by FETCHING
 * `/api/themes/<name>` and writing the variables onto documentElement. The
 * inline bootstrap script in app/layout.tsx can only set `data-theme` before
 * first paint, so until that fetch resolved the page painted with the default
 * palette — a visible flash on every reload with a non-default theme.
 *
 * With these rules present in the initial CSS, setting `data-theme` in the
 * bootstrap script is enough to paint correctly on the first frame.
 *
 * Usage: node scripts/generate-theme-css.mjs   (run by `npm run build` prebuild)
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const openchamberDir = join(root, "lib", "theme", "openchamber");
const outputPath = join(root, "app", "theme-presets.css");

// Only the variables that decide the first paint. Anything theme-derived and
// expensive (color-mix() status tokens, syntax colors) is left to the runtime
// fetch; these are the ones that cause a visible flash.
const PAINT_VARS = [
  "--bg", "--bg-panel", "--bg-secondary", "--bg-card", "--bg-hover", "--bg-selected",
  "--border", "--border-hover",
  "--text", "--text-muted", "--text-dim",
  "--accent", "--accent-hover",
  "--user-bg", "--assistant-bg", "--tool-bg",
  "--accent-red", "--accent-green", "--accent-orange",
  "--status-error", "--status-warning", "--status-success", "--status-info",
];

/** QT palettes are defined inline in lib/theme.ts; read them from source so
 *  there is exactly one place to edit a theme. */
function readQtThemeSets() {
  const source = readFileSync(join(root, "lib", "theme.ts"), "utf8");
  const start = source.indexOf("const BUILTIN_THEME_SETS");
  const end = source.indexOf("// ─── OpenChamber built-in themes");
  const block = source.slice(start, end);
  const sets = {};
  // Each entry is `name: { displayName, light: {...}, dark: {...} }` with one
  // JSON-ish object per line. Parse the per-variant objects directly.
  const entryRe = /^  ([a-z0-9-]+): \{\n    displayName: "([^"]+)",\n    light: (\{[^\n]+\}),\n    dark: (\{[^\n]+\}),\n  \},/gm;
  let match;
  while ((match = entryRe.exec(block)) !== null) {
    const [, name, displayName, lightRaw, darkRaw] = match;
    sets[name] = {
      displayName,
      light: parseInlineObject(lightRaw),
      dark: parseInlineObject(darkRaw),
    };
  }
  return sets;
}

/** Turn `{ bg: "#fff", ... }` into a plain object (values are quoted strings). */
function parseInlineObject(raw) {
  const result = {};
  const pairRe = /([a-zA-Z]+): "([^"]*)"/g;
  let match;
  while ((match = pairRe.exec(raw)) !== null) result[match[1]] = match[2];
  return result;
}

function readOpenChamberThemeSets() {
  const sets = {};
  for (const entry of readdirSync(openchamberDir)) {
    if (!entry.endsWith(".json")) continue;
    const parsed = JSON.parse(readFileSync(join(openchamberDir, entry), "utf8"));
    if (!parsed || typeof parsed !== "object") continue;
    sets[entry.replace(/\.json$/, "")] = parsed;
  }
  return sets;
}

function variantToVars(colors) {
  return {
    "--bg": colors.bg,
    "--bg-panel": colors.panel,
    "--bg-secondary": colors.panel,
    "--bg-card": colors.panel,
    "--bg-hover": colors.hover,
    "--bg-selected": colors.selected,
    "--border": colors.border,
    "--border-hover": colors.accentHover,
    "--text": colors.text,
    "--text-muted": colors.muted,
    "--text-dim": colors.dim,
    "--accent": colors.accent,
    "--accent-hover": colors.accentHover,
    "--user-bg": colors.userBg,
    "--assistant-bg": colors.assistantBg,
    "--tool-bg": colors.toolBg,
    "--accent-red": colors.red,
    "--accent-green": colors.green,
    "--accent-orange": colors.orange,
    "--status-error": colors.red,
    "--status-warning": colors.orange,
    "--status-success": colors.green,
    "--status-info": colors.accent,
  };
}

function build() {
  // OpenChamber first, QT second: QT wins name collisions, matching
  // ALL_BUILTIN_THEME_SETS in lib/theme.ts.
  const sets = { ...readOpenChamberThemeSets(), ...readQtThemeSets() };
  const lines = [
    "/* GENERATED by scripts/generate-theme-css.mjs — do not edit by hand. */",
    "/* Static theme variables so the first paint matches the saved theme. */",
    "",
  ];
  let count = 0;
  for (const [name, theme] of Object.entries(sets)) {
    for (const variant of ["light", "dark"]) {
      const colors = theme[variant];
      if (!colors) continue;
      const vars = variantToVars(colors);
      const selector = variant === "dark"
        ? `html.dark[data-theme="${name}"]`
        : `html:not(.dark)[data-theme="${name}"]`;
      lines.push(`${selector} {`);
      for (const key of PAINT_VARS) {
        if (vars[key] === undefined) continue;
        lines.push(`  ${key}: ${vars[key]};`);
      }
      lines.push("}", "");
      count += 1;
    }
  }
  writeFileSync(outputPath, `${lines.join("\n").trimEnd()}\n`, "utf8");
  console.log(`[theme-css] wrote ${count} variant blocks for ${Object.keys(sets).length} themes -> ${outputPath}`);
}

build();
